SELECT CASE WHEN
       count(*) >0 AND
       COALESCE(sum(CASE WHEN CURRENT_STATE <> NEW_STATE THEN 1 ELSE 0 END),-1) = 0
       THEN '1' ELSE '0'
       END AS FACTIVA_INDEXED
FROM SERVER_STATES
WHERE TOPIC IN ('WLM_FPFA_INDEXES')
AND 1 = ( SELECT 1 FROM LIST_DEFINITION WHERE IMPORT_STATE =-5 AND LIST_DEFINITION_NAME= 'FACTIVA PFA'
AND IMPORT_COMPLETED_TIMESTAMP IS NOT NULL AND IS_DELETED =0)
AND 0 = (SELECT count(*) FROM WLM_MODEL)
OR
(TOPIC IN ( 'WLM_IGS_WLM_FPFA_INDEXES.1000')
AND 1 = ( SELECT 1 FROM LIST_DEFINITION WHERE IMPORT_STATE =-5 AND LIST_DEFINITION_NAME= 'FACTIVA PFA'
AND IMPORT_COMPLETED_TIMESTAMP IS NOT NULL AND IS_DELETED =0)
AND 1 <= (SELECT count(*) FROM WLM_MODEL)
)